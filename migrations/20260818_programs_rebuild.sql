-- ── Lookups ──────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.program_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  description text,
  sort_order int NOT NULL DEFAULT 0,
  active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.shops (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  location text,
  shop_type text,
  tank_labor_rate numeric,
  freight_labor_rate numeric,
  switch_fees numeric,
  address text,
  serving_rr text,
  connecting_rr text,
  admin_contact_name text,
  admin_contact_email text,
  admin_contact_office text,
  admin_contact_cell text,
  commercial_contact_name text,
  commercial_contact_email text,
  commercial_contact_office text,
  commercial_contact_cell text
);

CREATE TABLE IF NOT EXISTS public.scrap_yards (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  location text,
  rate_per_gross_ton numeric,
  serving_rr text,
  connecting_rr text,
  address text,
  contact_name text,
  contact_email text,
  contact_office text,
  contact_cell text
);

CREATE TABLE IF NOT EXISTS public.program_field_defs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id bigint NOT NULL REFERENCES public.program_categories(id) ON DELETE CASCADE,
  field_key text NOT NULL,
  label text NOT NULL,
  field_type text NOT NULL,
  section text,
  sort_order int NOT NULL DEFAULT 0,
  select_options text[],
  UNIQUE (category_id, field_key),
  CONSTRAINT program_field_defs_type_check
    CHECK (field_type = ANY (ARRAY['text','number','currency','date','boolean','select']))
);

