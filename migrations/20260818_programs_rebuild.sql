-- ── program_documents ────────────────────────────────────────────────────────

ALTER TABLE public.program_documents ADD COLUMN IF NOT EXISTS document_category text;
UPDATE public.program_documents
SET document_category = CASE lower(coalesce(doc_type, ''))
  WHEN 'sow' THEN 'sow'
  WHEN 'car list' THEN 'car_drawing'
  WHEN 'inspection report' THEN 'report'
  WHEN 'photo' THEN 'photo'
  ELSE 'other'
END
WHERE document_category IS NULL;
ALTER TABLE public.program_documents ALTER COLUMN document_category SET DEFAULT 'other';
ALTER TABLE public.program_documents ALTER COLUMN document_category SET NOT NULL;

