-- ── car-line documents + activity ────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.program_car_documents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  program_car_id bigint NOT NULL REFERENCES public.program_cars(id) ON DELETE CASCADE,
  document_category text NOT NULL DEFAULT 'other',
  file_path text NOT NULL,
  file_name text NOT NULL,
  file_size_bytes bigint,
  uploaded_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  uploaded_at timestamptz NOT NULL DEFAULT now(),
  notes text
);
CREATE INDEX IF NOT EXISTS idx_program_car_documents_car
  ON public.program_car_documents (program_car_id);

CREATE TABLE IF NOT EXISTS public.program_activity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  program_id bigint NOT NULL REFERENCES public.programs(id) ON DELETE CASCADE,
  program_car_id bigint REFERENCES public.program_cars(id) ON DELETE SET NULL,
  railcar_id bigint REFERENCES public.railcars(id) ON DELETE SET NULL,
  action text NOT NULL,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  actor uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_program_activity_program
  ON public.program_activity (program_id, created_at DESC);

