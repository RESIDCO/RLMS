ALTER TABLE public.programs DROP CONSTRAINT IF EXISTS programs_status_check;
UPDATE public.programs SET status = CASE status
  WHEN 'active' THEN 'open'
  WHEN 'draft' THEN 'on_hold'
  WHEN 'archived' THEN 'complete'
  ELSE status
END
WHERE status IN ('active', 'draft', 'archived');
ALTER TABLE public.programs ALTER COLUMN status SET DEFAULT 'open';
ALTER TABLE public.programs ADD CONSTRAINT programs_status_check
  CHECK (status = ANY (ARRAY['open'::text, 'on_hold'::text, 'complete'::text]));

