  h.created_by,
  'ui',
  h.created_at,
  'car_status_history',
  h.id
FROM public.car_status_history h
WHERE h.car_id IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM public.activity_log a
    WHERE a.source_table = 'car_status_history' AND a.source_id = h.id
  );

-- On / off rent
INSERT INTO public.activity_log (
  entity_type, entity_id, railcar_id, action, detail, actor, source, occurred_at, source_table, source_id
)
SELECT
  'railcar',
  e.car_id,
  e.car_id,
  'rent_event',
  jsonb_strip_nulls(jsonb_build_object(
    'event_type', e.event_type,
    'event_date', e.event_date,
    'reason', e.reason
  )),
  e.created_by,
  'ui',
  COALESCE(e.event_date::timestamptz, e.created_at, now()),
  'rent_events',
  e.id
FROM public.rent_events e
WHERE e.car_id IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM public.activity_log a
    WHERE a.source_table = 'rent_events' AND a.source_id = e.id
  );

-- Real assignment / Move Cars rows only — skip VCF period placeholders
INSERT INTO public.activity_log (
  entity_type, entity_id, railcar_id, rider_id, action, detail, actor, source, occurred_at, source_table, source_id
)
SELECT
  'railcar',
  h.railcar_id,
  h.railcar_id,
  h.to_rider_id,
  'reassignment',
  jsonb_strip_nulls(jsonb_build_object(
    'from_rider_id', h.from_rider_id,
    'to_rider_id', h.to_rider_id,
    'from_fleet', h.from_fleet_name,
    'to_fleet', h.to_fleet_name,
    'reason', h.reason
  )),
  COALESCE(h.moved_by, 'system'),
  'ui',
  COALESCE(h.moved_at, now()),
  'assignment_history',
  h.id
FROM public.assignment_history h
WHERE h.railcar_id IS NOT NULL
  AND COALESCE(h.moved_by, '') <> 'vcf-import'
  AND COALESCE(h.reason, '') NOT ILIKE '%V_VALID_CARS assignment period%'
  AND NOT EXISTS (
    SELECT 1 FROM public.activity_log a
    WHERE a.source_table = 'assignment_history' AND a.source_id = h.id
  );

-- Legacy single-field railcar notes → one timestamped entry each
INSERT INTO public.activity_log (
  entity_type, entity_id, railcar_id, action, detail, actor, source, occurred_at, source_table, source_id
)
SELECT
  'railcar',
  r.id,
  r.id,
  'note',
  jsonb_build_object('body', r.notes),
  'legacy',
  'legacy',
  COALESCE(r.updated_at, now()),
  'railcars.notes',
