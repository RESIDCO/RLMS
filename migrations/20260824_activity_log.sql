-- Unified activity / lineage log for railcars and riders.
-- Specialized tables (car_number_history, assignment_history, car_status_history,
-- rent_events) stay as sources of truth; this table is the merged, queryable feed.

CREATE TABLE IF NOT EXISTS public.activity_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type text NOT NULL,
  entity_id bigint NOT NULL,
  railcar_id bigint REFERENCES public.railcars (id) ON DELETE SET NULL,
  rider_id bigint REFERENCES public.riders (id) ON DELETE SET NULL,
  action text NOT NULL,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  actor text,
  source text NOT NULL DEFAULT 'ui',
  occurred_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  source_table text,
  source_id bigint,
  CONSTRAINT activity_log_entity_type_check
    CHECK (entity_type = ANY (ARRAY['railcar'::text, 'rider'::text]))
);

CREATE INDEX IF NOT EXISTS idx_activity_log_railcar_occurred
  ON public.activity_log (railcar_id, occurred_at DESC)
  WHERE railcar_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_activity_log_rider_occurred
  ON public.activity_log (rider_id, occurred_at DESC)
  WHERE rider_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_activity_log_entity
  ON public.activity_log (entity_type, entity_id, occurred_at DESC);

CREATE INDEX IF NOT EXISTS idx_activity_log_occurred
  ON public.activity_log (occurred_at DESC);

CREATE UNIQUE INDEX IF NOT EXISTS uq_activity_log_source_row
  ON public.activity_log (source_table, source_id)
  WHERE source_table IS NOT NULL AND source_id IS NOT NULL;

COMMENT ON TABLE public.activity_log IS
  'Append-only lineage for cars and riders: mark changes, status, rent, assignments, notes.';

-- Reporting mark / number changes (including VCF remarks — those are real lineage)
INSERT INTO public.activity_log (
  entity_type, entity_id, railcar_id, action, detail, actor, source, occurred_at, source_table, source_id
)
SELECT
  'railcar',
  h.railcar_id,
  h.railcar_id,
  'mark_change',
  jsonb_strip_nulls(jsonb_build_object(
    'from', NULLIF(trim(concat_ws(' ', h.old_car_initial, h.old_car_number)), ''),
    'to', NULLIF(trim(concat_ws(' ', h.new_car_initial, h.new_car_number)), ''),
    'reason', h.reason
  )),
  COALESCE(h.changed_by, 'system'),
  CASE WHEN h.changed_by = 'vcf-import' THEN 'vcf-import' ELSE 'ui' END,
  COALESCE(h.changed_at, now()),
  'car_number_history',
  h.id
FROM public.car_number_history h
WHERE h.railcar_id IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM public.activity_log a
    WHERE a.source_table = 'car_number_history' AND a.source_id = h.id
  );

-- Active status Inactive / Reactivate
