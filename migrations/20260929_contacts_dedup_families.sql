DO $$ BEGIN
  CREATE TYPE public.dedup_candidate_kind AS ENUM ('agent_contact', 'company_family', 'company_duplicate');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  CREATE TYPE public.dedup_candidate_status AS ENUM ('auto_applied', 'pending_review', 'approved', 'rejected');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS public.contact_company_dedup_candidates (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind                    public.dedup_candidate_kind NOT NULL,
  company_contact_id      bigint REFERENCES public.company_contacts(id) ON DELETE CASCADE,
  agent_organization_name text,
  agent_home_company_id   bigint REFERENCES public.companies(id),
  company_id_a            bigint REFERENCES public.companies(id),
  company_id_b            bigint REFERENCES public.companies(id),
  email                   text,
  signal                  text NOT NULL,
  confidence              numeric,
  note                    text,
  status                  public.dedup_candidate_status NOT NULL DEFAULT 'pending_review',
  reviewed_by             uuid REFERENCES auth.users(id),
  reviewed_at             timestamptz,
  created_at              timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_dedup_candidates_status ON public.contact_company_dedup_candidates(status);
CREATE INDEX IF NOT EXISTS idx_dedup_candidates_kind ON public.contact_company_dedup_candidates(kind);

