-- Rev 6: agent-contact tags, company families, dedup queue, company-level lease links.
-- Additive. Does not alter accounts, master_leases, riders, or railcars columns.
-- Does not auto-merge any companies.

CREATE OR REPLACE FUNCTION public.clean_company_name(p_name text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT regexp_replace(
    regexp_replace(
      regexp_replace(
        lower(regexp_replace(coalesce(p_name, ''), '&', ' and ', 'g')),
        '[^a-z0-9]+', ' ', 'g'
      ),
      '\m(incorporated|corporation|company|limited|the|inc|llc|llp|corp|ltd|lp|plc|sa|co)\M',
      '',
      'g'
    ),
    '\s+',
    '',
    'g'
  );
$$;

