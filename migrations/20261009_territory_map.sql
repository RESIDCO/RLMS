CREATE OR REPLACE VIEW public.v_contact_geo AS
WITH norm AS (
  SELECT cc.id AS contact_id, cc.company_id, cc.name AS contact_name, cc.title, cc.email,
         cc.city, upper(nullif(trim(cc.state),'')) AS state_raw, cc.zip AS zip_raw,
         CASE WHEN upper(nullif(trim(cc.state),'')) IS NOT NULL
                   AND upper(trim(cc.state)) NOT IN (SELECT usps FROM public.geo_states) THEN NULL
              WHEN trim(cc.zip) ~ '^[0-9]{5}(-[0-9]{4})?$' THEN left(trim(cc.zip),5)
              WHEN trim(cc.zip) ~ '^[0-9]{4}$' THEN lpad(trim(cc.zip),5,'0') END AS zip5
  FROM public.company_contacts cc
), state_owner AS (
  SELECT c.state_usps,
         CASE WHEN count(DISTINCT a.owner_initials)=1 AND bool_and(a.owner_initials IS NOT NULL)
              THEN min(a.owner_initials) END AS owner_initials
  FROM public.geo_counties c
  JOIN public.territory_county_assignments a USING (county_fips)
  GROUP BY c.state_usps
)
SELECT n.contact_id, n.company_id, n.contact_name, n.title, n.email,
       co.name AS company_name, co.relationship_type, co.priority_tier, co.status AS pipeline_status,
       co.account_id, ac.account_manager,
       n.city, n.state_raw, n.zip_raw, n.zip5,
       z.county_fips,
       coalesce(z.state_usps, CASE WHEN gs.usps IS NOT NULL THEN gs.usps END) AS state_usps,
       z.lat, z.lng,
       CASE WHEN z.county_fips IS NOT NULL THEN 'mapped_county'
            WHEN gs.usps IS NOT NULL THEN 'state_only'
            WHEN n.state_raw IN ('AB','BC','MB','NB','NL','NS','NT','NU','ON','PE','QC','SK','YT') THEN 'outside_us_canada'
            WHEN n.state_raw IS NOT NULL THEN 'outside_us_other'
            ELSE 'no_location' END AS location_status,
       coalesce(tca.owner_initials, so.owner_initials) AS territory_owner,
       (z.county_fips IS NULL AND gs.usps IS NOT NULL AND so.owner_initials IS NULL) AS split_state_unresolved
FROM norm n
JOIN public.companies co ON co.id = n.company_id
LEFT JOIN public.accounts ac ON ac.id = co.account_id
LEFT JOIN public.geo_zips z ON z.zip = n.zip5
LEFT JOIN public.geo_states gs ON gs.usps = n.state_raw
LEFT JOIN public.territory_county_assignments tca ON tca.county_fips = z.county_fips
LEFT JOIN state_owner so ON so.state_usps = coalesce(z.state_usps, gs.usps);

COMMENT ON VIEW public.v_contact_geo IS
  'Read-only contact geography for the Territory Map. One row per company_contacts row. No lease income.';

CREATE OR REPLACE FUNCTION public.assign_territory_groups(
  p_groups jsonb,
  p_who text,
  p_note text,
  p_cs uuid
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
  g jsonb;
  v_counties text[];
  v_owner text;
  v_logged int := 0;
BEGIN
  IF p_cs IS NULL THEN
    RAISE EXCEPTION 'change_set_id is required';
  END IF;
  IF jsonb_typeof(p_groups) <> 'array' OR jsonb_array_length(p_groups) = 0 THEN
    RAISE EXCEPTION 'groups must be a non-empty JSON array';
  END IF;

  FOR g IN SELECT value FROM jsonb_array_elements(p_groups) LOOP
    SELECT coalesce(array_agg(x), ARRAY[]::text[])
      INTO v_counties
    FROM jsonb_array_elements_text(coalesce(g->'counties', '[]'::jsonb)) AS x
    WHERE x ~ '^[0-9]{5}$';

    IF cardinality(v_counties) = 0 THEN
      CONTINUE;
    END IF;

    IF jsonb_typeof(g->'owner') = 'null' OR g->>'owner' IS NULL OR btrim(g->>'owner') = '' THEN
      v_owner := NULL;
    ELSE
      v_owner := upper(btrim(g->>'owner'));
    END IF;

    WITH old AS (
      SELECT a.county_fips, a.owner_initials
      FROM public.territory_county_assignments a
      WHERE a.county_fips = ANY (v_counties)
    ),
    upd AS (
      UPDATE public.territory_county_assignments a
         SET owner_initials = v_owner, updated_at = now(), updated_by = p_who
       WHERE a.county_fips = ANY (v_counties)
         AND a.owner_initials IS DISTINCT FROM v_owner
      RETURNING a.county_fips
    )
    INSERT INTO public.territory_change_log (change_set_id, county_fips, from_owner, to_owner, changed_by, note)
    SELECT p_cs, o.county_fips, o.owner_initials, v_owner, p_who, p_note
    FROM old o
    JOIN upd u USING (county_fips);
  END LOOP;

  SELECT count(*)::int INTO v_logged FROM public.territory_change_log WHERE change_set_id = p_cs;
  RETURN jsonb_build_object('updated', v_logged, 'logged', v_logged, 'change_set_id', p_cs);
END;
$$;

CREATE OR REPLACE FUNCTION public.revert_territory_change_set(
  p_old_cs uuid,
  p_who text,
  p_new_cs uuid
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
  v_groups jsonb;
BEGIN
  IF p_old_cs IS NULL OR p_new_cs IS NULL THEN
    RAISE EXCEPTION 'change_set ids are required';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.territory_change_log WHERE change_set_id = p_old_cs) THEN
    RAISE EXCEPTION 'Unknown change_set_id';
  END IF;

  SELECT coalesce(jsonb_agg(jsonb_build_object(
           'counties', g.counties,
           'owner', g.from_owner
         )), '[]'::jsonb)
    INTO v_groups
  FROM (
    SELECT from_owner, array_agg(county_fips) AS counties
    FROM public.territory_change_log
    WHERE change_set_id = p_old_cs
    GROUP BY from_owner
  ) g;

  RETURN public.assign_territory_groups(
    v_groups,
    p_who,
    'Revert of ' || p_old_cs::text,
    p_new_cs
  );
END;
$$;

