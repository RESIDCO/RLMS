-- RLMS Territory Map — additive schema + seed + assign/revert wrappers.
-- Does not alter accounts, companies, company_contacts, leases, riders, or railcars.

-- 1. Territory owners (legend/colors; initials match accounts.account_manager)
CREATE TABLE IF NOT EXISTS public.territory_owners (
  initials    text PRIMARY KEY CHECK (initials = upper(initials) AND length(initials) BETWEEN 2 AND 4),
  full_name   text NOT NULL,
  color_hex   text NOT NULL CHECK (color_hex ~ '^#[0-9A-Fa-f]{6}$'),
  is_active   boolean NOT NULL DEFAULT true,
  sort_order  integer NOT NULL DEFAULT 100,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.geo_states (
  usps  text PRIMARY KEY CHECK (length(usps) = 2),
  fips  text NOT NULL UNIQUE CHECK (fips ~ '^[0-9]{2}$'),
  name  text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.geo_counties (
  county_fips text PRIMARY KEY CHECK (county_fips ~ '^[0-9]{5}$'),
  state_usps  text NOT NULL REFERENCES public.geo_states(usps),
  name        text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_geo_counties_state ON public.geo_counties(state_usps);

CREATE TABLE IF NOT EXISTS public.geo_zips (
  zip         text PRIMARY KEY CHECK (zip ~ '^[0-9]{5}$'),
  county_fips text REFERENCES public.geo_counties(county_fips),
  state_usps  text REFERENCES public.geo_states(usps),
  lat         numeric(9,6),
  lng         numeric(9,6)
);
CREATE INDEX IF NOT EXISTS idx_geo_zips_county ON public.geo_zips(county_fips);

CREATE TABLE IF NOT EXISTS public.territory_county_assignments (
  county_fips    text PRIMARY KEY REFERENCES public.geo_counties(county_fips),
  owner_initials text REFERENCES public.territory_owners(initials),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  updated_by     text
);
CREATE INDEX IF NOT EXISTS idx_tca_owner ON public.territory_county_assignments(owner_initials);

CREATE TABLE IF NOT EXISTS public.territory_change_log (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  change_set_id uuid NOT NULL,
  county_fips   text NOT NULL REFERENCES public.geo_counties(county_fips),
  from_owner    text,
  to_owner      text,
  changed_by    text,
  changed_at    timestamptz NOT NULL DEFAULT now(),
  note          text
);
CREATE INDEX IF NOT EXISTS idx_tcl_set ON public.territory_change_log(change_set_id);
CREATE INDEX IF NOT EXISTS idx_tcl_county ON public.territory_change_log(county_fips, changed_at DESC);

CREATE TABLE IF NOT EXISTS public.territory_state_seed (
  state_usps     text PRIMARY KEY REFERENCES public.geo_states(usps),
  owner_initials text NOT NULL REFERENCES public.territory_owners(initials)
);

