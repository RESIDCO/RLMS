-- Exact Asset Report Lease Exp dates, multi-term schedules, text statuses.
-- Do not back-fill July/August. Re-drop the current month after this ships.

ALTER TABLE public.rider_financial_summary
  ADD COLUMN IF NOT EXISTS lease_exp_date date;

COMMENT ON COLUMN public.rider_financial_summary.lease_exp_date IS
  'Asset Report Lease Exp (per rider deal). Distinct from VCF car-level lease_end_date.';

ALTER TABLE public.riders
  ADD COLUMN IF NOT EXISTS lease_status text,
  ADD COLUMN IF NOT EXISTS lease_status_snapshot_month date;

COMMENT ON COLUMN public.riders.lease_status IS
  'Asset Report Lease Exp text when the cell is not a date (AVAILABLE, MTM, SCRAPPING, …).';
COMMENT ON COLUMN public.riders.lease_status_snapshot_month IS
  'rider_financial_summary.snapshot_month that produced lease_status.';

CREATE TABLE IF NOT EXISTS public.rider_lease_terms (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_month date NOT NULL,
  rider_id text NOT NULL,
  entity text NOT NULL,
  term_end date,
  status_text text,
  car_count integer NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS rider_lease_terms_uniq
  ON public.rider_lease_terms (
    snapshot_month,
    rider_id,
    entity,
    coalesce(term_end, '0001-01-01'::date),
    coalesce(status_text, '')
  );

CREATE INDEX IF NOT EXISTS rider_lease_terms_snap_rider
  ON public.rider_lease_terms (snapshot_month, rider_id);

COMMENT ON TABLE public.rider_lease_terms IS
  'One row per distinct Asset Report Lease Exp value per rider/entity/snapshot. Replaced per month.';

GRANT SELECT ON public.rider_lease_terms TO anon, authenticated;
GRANT ALL ON public.rider_lease_terms TO service_role;
