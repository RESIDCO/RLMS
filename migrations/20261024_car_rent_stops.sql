-- Rental abatement / rent stops. Does not repurpose public.rent_events
-- (that table still has 0 rows, RLS off, and remaining API/UI references).
-- Off-rent KPI logic (assignment_history.end_date / v_rlms_kpi_car_rows.off_rent) is unchanged.

CREATE TABLE IF NOT EXISTS public.car_rent_stops (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  railcar_id bigint NOT NULL REFERENCES public.railcars(id) ON DELETE CASCADE,
  assignment_id bigint REFERENCES public.railcar_assignments(id) ON DELETE SET NULL,
  rider_id bigint REFERENCES public.riders(id) ON DELETE SET NULL,
  lease_ref text,
  lessee_snapshot text,
  type text NOT NULL CHECK (type IN ('Abatement', 'Off rent')),
  stop_date date NOT NULL,
  expected_resume_date date,
  actual_resume_date date,
  reason text NOT NULL CHECK (reason IN ('quality repair', 'goodwill', 'damage', 'dispute', 'other')),
  reason_other text,
  note text,
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  converted_from_id bigint REFERENCES public.car_rent_stops(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS car_rent_stops_one_open
  ON public.car_rent_stops (railcar_id)
  WHERE actual_resume_date IS NULL;

CREATE INDEX IF NOT EXISTS car_rent_stops_railcar_idx
  ON public.car_rent_stops (railcar_id, actual_resume_date);

CREATE TABLE IF NOT EXISTS public.car_rent_stops_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stop_id bigint,
  op text NOT NULL CHECK (op IN ('INSERT', 'UPDATE', 'DELETE')),
  old_row jsonb,
  new_row jsonb,
  actor uuid,
  at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.car_rent_stops_audit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.car_rent_stops_history (stop_id, op, old_row, new_row, actor)
    VALUES (NEW.id, TG_OP, NULL, to_jsonb(NEW), NEW.created_by);
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    INSERT INTO public.car_rent_stops_history (stop_id, op, old_row, new_row, actor)
    VALUES (NEW.id, TG_OP, to_jsonb(OLD), to_jsonb(NEW), NEW.created_by);
    RETURN NEW;
  ELSE
    INSERT INTO public.car_rent_stops_history (stop_id, op, old_row, new_row, actor)
    VALUES (OLD.id, TG_OP, to_jsonb(OLD), NULL, OLD.created_by);
    RETURN OLD;
  END IF;
END;
$$;

DROP TRIGGER IF EXISTS trg_car_rent_stops_audit ON public.car_rent_stops;
CREATE TRIGGER trg_car_rent_stops_audit
  AFTER INSERT OR UPDATE OR DELETE ON public.car_rent_stops
  FOR EACH ROW EXECUTE FUNCTION public.car_rent_stops_audit();

DROP TRIGGER IF EXISTS trg_car_rent_stops_updated_at ON public.car_rent_stops;
CREATE TRIGGER trg_car_rent_stops_updated_at
  BEFORE UPDATE ON public.car_rent_stops
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

