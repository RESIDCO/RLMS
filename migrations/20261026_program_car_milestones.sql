-- Per-step program-car milestone trail. Latest row is mirrored on
-- program_cars.milestone / milestone_at. Program "done" stays
-- outcome_reached_at (arrived at committed destination); terminal
-- steps (scrapped / sold / on rent) are extra trail rows after that.

CREATE TABLE IF NOT EXISTS public.program_car_milestones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  program_car_id bigint NOT NULL REFERENCES public.program_cars(id) ON DELETE CASCADE,
  milestone text NOT NULL,
  milestone_date date NOT NULL,
  note text,
  actor text,
  change_group uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS program_car_milestones_car_date_idx
  ON public.program_car_milestones (program_car_id, milestone_date, id);

ALTER TABLE public.program_car_milestones ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.program_car_milestones FROM PUBLIC, anon;
GRANT SELECT ON public.program_car_milestones TO authenticated;
GRANT ALL ON public.program_car_milestones TO service_role;

DROP POLICY IF EXISTS program_car_milestones_select_authenticated ON public.program_car_milestones;
CREATE POLICY program_car_milestones_select_authenticated ON public.program_car_milestones
  FOR SELECT TO authenticated
  USING (true);
