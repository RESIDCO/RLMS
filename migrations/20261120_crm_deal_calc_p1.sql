create function public.crm_calc_scenario_line_matches() returns trigger
  language plpgsql
  set search_path = public, pg_temp
as $$
begin
  if new.opportunity_line_id is not null and not exists (
       select 1 from public.opportunity_lines l
       where l.id = new.opportunity_line_id and l.opportunity_id = new.opportunity_id) then
    raise exception 'opportunity_line % is not on opportunity %', new.opportunity_line_id, new.opportunity_id;
  end if;
  return new;
end $$;

revoke all on function public.crm_calc_scenario_line_matches() from public, anon, authenticated;
grant execute on function public.crm_calc_scenario_line_matches() to service_role;

create trigger trg_deal_calc_scenarios_line_matches
  before insert or update of opportunity_line_id, opportunity_id on public.deal_calc_scenarios
  for each row when (new.opportunity_line_id is not null)
  execute function public.crm_calc_scenario_line_matches();

