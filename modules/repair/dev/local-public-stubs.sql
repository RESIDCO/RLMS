-- Minimal public stubs so repair.cars_ref and VCF checks work on an empty local DB.
-- Does not mirror full RLMS schema.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.railcars (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  car_number text NOT NULL,
  car_initial text,
  reporting_marks text,
  active boolean DEFAULT true,
  rider_external_id text,
  assignment_label text,
  current_assignment_id text,
  lessee_name text,
  comment_event_note text,
  fleet_status text,
  managed text,
  managed_category text,
  -- RLMS owning entity: Main | Coal | Rail Partners Select (OWNER_UI entity tags)
  entity text
);

ALTER TABLE public.railcars ADD COLUMN IF NOT EXISTS entity text;

CREATE TABLE IF NOT EXISTS public.v_valid_export_rows_data (
  export_src smallint,
  export_id bigint,
  car_initial text,
  car_number text,
  active integer,
  rider text,
  assignment text,
  assignment_id text,
  lessee text,
  start_date text,
  end_date text
);

CREATE OR REPLACE VIEW public.v_valid_export_rows AS
SELECT * FROM public.v_valid_export_rows_data;

