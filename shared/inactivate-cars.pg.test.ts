/* eslint-disable no-console */
/**
 * Executes inactivate_railcars on a throwaway Postgres cluster.
 * Run: npx tsx shared/inactivate-cars.pg.test.ts
 *
 * The migration file is applied only to this temporary database.
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const PG_BIN = ["/usr/lib/postgresql/16/bin", "/usr/lib/postgresql/17/bin", "/usr/lib/postgresql/15/bin"].find((dir) =>
  existsSync(join(dir, "initdb")),
);

let passed = 0;
let failed = 0;
function ok(cond: boolean, label: string) {
  if (cond) passed += 1;
  else {
    failed += 1;
    console.error("FAIL", label);
  }
}

if (!PG_BIN) {
  console.error("FAIL postgres binaries not found");
  process.exit(1);
}

const root = mkdtempSync(join(tmpdir(), "inactivate-pg-"));
const data = join(root, "data");
const sock = root;
const port = "55441";
const migration = join(import.meta.dirname, "../migrations/20261114_inactivate_railcars.sql");

function bin(name: string): string {
  return join(PG_BIN!, name);
}

function run(cmd: string, args: string[], input?: string): { status: number; stdout: string; stderr: string } {
  const res = spawnSync(cmd, args, { encoding: "utf8", input });
  return { status: res.status ?? 1, stdout: res.stdout ?? "", stderr: res.stderr ?? "" };
}

function psql(sql: string, database = "inactivate"): string {
  const res = run(bin("psql"), ["-h", sock, "-p", port, "-U", "postgres", "-d", database, "-v", "ON_ERROR_STOP=1", "-tA", "-c", sql]);
  if (res.status !== 0) throw new Error(res.stderr || res.stdout);
  return res.stdout.trim();
}

function psqlFile(file: string) {
  const res = run(bin("psql"), ["-h", sock, "-p", port, "-U", "postgres", "-d", "inactivate", "-v", "ON_ERROR_STOP=1", "-f", file]);
  if (res.status !== 0) throw new Error(res.stderr || res.stdout);
}

try {
  const init = run(bin("initdb"), ["-D", data, "--username=postgres", "--auth=trust", "--no-sync"]);
  if (init.status !== 0) throw new Error(init.stderr || init.stdout);
  const start = run(bin("pg_ctl"), ["-D", data, "-o", `-p ${port} -k ${sock} -c listen_addresses=`, "-l", join(root, "log"), "start"]);
  if (start.status !== 0) throw new Error(start.stderr || start.stdout);
  psql("CREATE DATABASE inactivate", "postgres");
  psql(`
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE ROLE service_role;
    CREATE TABLE public.railcars (
      id bigint PRIMARY KEY,
      car_number text NOT NULL,
      reporting_marks text NOT NULL,
      status text NOT NULL DEFAULT 'Active/In-Service',
      active boolean NOT NULL DEFAULT true,
      active_status text,
      active_source text NOT NULL DEFAULT 'auto',
      rider_external_id text
    );
    CREATE TABLE public.assignment_history (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      railcar_id bigint NOT NULL REFERENCES public.railcars(id),
      end_date date,
      active boolean,
      rider_external_id text
    );
    CREATE TABLE public.car_status_history (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      car_id bigint NOT NULL REFERENCES public.railcars(id),
      event_type text NOT NULL,
      reason text NOT NULL,
      created_by text NOT NULL,
      created_at timestamptz NOT NULL DEFAULT now(),
      from_status text,
      to_status text
    );
    CREATE TABLE public.activity_log (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      entity_type text NOT NULL,
      entity_id bigint NOT NULL,
      railcar_id bigint,
      rider_id bigint,
      action text NOT NULL,
      detail jsonb NOT NULL DEFAULT '{}'::jsonb,
      actor text,
      source text NOT NULL DEFAULT 'ui',
      occurred_at timestamptz NOT NULL DEFAULT now(),
      change_group uuid,
      table_name text,
      row_pk bigint,
      before jsonb,
      after jsonb,
      undoable boolean NOT NULL DEFAULT true,
      undo_of bigint,
      undone_at timestamptz,
      undone_by text
    );
    CREATE TABLE public.rent_events (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      car_id bigint NOT NULL,
      event_type text NOT NULL,
      event_date date NOT NULL,
      reason text NOT NULL,
      created_by text NOT NULL
    );
    INSERT INTO public.rent_events (car_id, event_type, event_date, reason, created_by)
    VALUES (1, 'off', '2026-01-01', 'leave this row', 'seed');
    INSERT INTO public.railcars (id, car_number, reporting_marks, status, active, active_status, active_source, rider_external_id)
    VALUES
      (1, '310001', 'OFOX', 'Storage', true, 'Active', 'auto', '1503'),
      (2, '310002', 'OFOX', 'Bad Order', true, 'Active', 'auto', '1503'),
      (3, '310003', 'OFOX', 'Off-Lease', true, 'Active', 'auto', NULL),
      (4, '310004', 'OFOX', 'Scrapped', false, 'Inactive', 'auto', NULL);
    INSERT INTO public.assignment_history (railcar_id, end_date, active, rider_external_id)
    VALUES (1, NULL, true, '1503'), (2, NULL, true, '1503');
    CREATE TABLE public.car_rent_stops (
      id bigint PRIMARY KEY,
      railcar_id bigint NOT NULL,
      type text NOT NULL,
      stop_date date NOT NULL,
      actual_resume_date date
    );
    INSERT INTO public.car_rent_stops (id, railcar_id, type, stop_date, actual_resume_date)
    VALUES (40, 1, 'Off rent', '2026-10-01', NULL);
  `);
  psqlFile(migration);

  const refused = JSON.parse(psql(`
    SELECT public.inactivate_railcars(
      '[1,4]'::jsonb, 'sold', 'actor-1', 'tester@residco.com', false, NULL
    )::text
  `)) as { ok: boolean; error?: string };
  ok(refused.ok === false && (refused.error ?? "").includes("Already inactive"), "a frozen car refuses the batch");
  ok(psql("SELECT status || ':' || active::text FROM public.railcars WHERE id = 1") === "Storage:true", "refused batch did not change the ready car");
  ok(psql("SELECT count(*) FROM public.rent_events") === "1", "refused batch left the rent event row");

  const applied = JSON.parse(psql(`
    SELECT public.inactivate_railcars(
      '[1,2]'::jsonb, 'Destroyed by the railroad', 'actor-1', 'tester@residco.com', true, '2026-10-19'
    )::text
  `)) as { ok: boolean; change_group: string; applied: number; closed_assignments: number };
  ok(applied.ok === true && applied.applied === 2 && applied.closed_assignments === 2, "two cars inactivated and both assignments closed");
  ok(
    psql("SELECT id::text || ':' || status || ':' || active::text || ':' || active_source FROM public.railcars WHERE id IN (1, 2) ORDER BY id") ===
      "1:Inactive:false:manual\n2:Inactive:false:manual",
    "only Inactive sets active=false",
  );
  ok(psql("SELECT status || ':' || active::text FROM public.railcars WHERE id = 3") === "Off-Lease:true", "a car outside the batch stays active");
  ok(psql("SELECT status FROM public.railcars WHERE id = 4") === "Scrapped", "the already-inactive car was not rewritten");
  ok(psql("SELECT end_date::text || ':' || active::text FROM public.assignment_history WHERE railcar_id IN (1, 2) ORDER BY railcar_id") === "2026-10-19:false\n2026-10-19:false", "open assignments received the end date");
  ok(psql("SELECT count(*) FROM public.rent_events") === "1", "rent event row is untouched");
  ok(
    psql("SELECT id::text || ':' || type || ':' || stop_date::text || ':' || coalesce(actual_resume_date::text, '') FROM public.car_rent_stops") ===
      "40:Off rent:2026-10-01:",
    "off-rent stop date stays 2026-10-01 and the stop stays open",
  );
  ok(
    psql("SELECT end_date::text FROM public.assignment_history WHERE railcar_id = 1") === "2026-10-19",
    "inactivation date is the assignment end date, not the off-rent stop date",
  );
  ok(psql(`SELECT count(DISTINCT change_group) FROM public.activity_log WHERE change_group = '${applied.change_group}'`) === "1", "one change group");
  ok(
    psql(`SELECT count(*) FROM public.activity_log WHERE change_group = '${applied.change_group}' AND table_name = 'railcars' AND undoable IS TRUE`) === "2",
    "each car has an undoable railcar row",
  );
  ok(
    psql(`SELECT count(*) FROM public.activity_log WHERE change_group = '${applied.change_group}' AND table_name = 'assignment_history'`) === "2",
    "each closed assignment is in the same group",
  );
  ok(
    psql(`SELECT count(*) FROM public.activity_log WHERE change_group = '${applied.change_group}' AND table_name = 'car_rent_stops'`) === "0",
    "the change group does not capture a rent-stop write",
  );
  ok(psql("SELECT count(*) FROM public.car_status_history WHERE event_type = 'marked_inactive' AND reason = 'Destroyed by the railroad'") === "2", "history rows store the reason");

  const again = JSON.parse(psql(`
    SELECT public.inactivate_railcars(
      '[1]'::jsonb, 'again', 'actor-1', 'tester@residco.com', false, NULL
    )::text
  `)) as { ok: boolean };
  ok(again.ok === false, "a second inactivate does not write again");

  const openLeft = JSON.parse(psql(`
    SELECT public.inactivate_railcars(
      '[3]'::jsonb, 'no assignment', 'actor-1', 'tester@residco.com', false, NULL
    )::text
  `)) as { ok: boolean; applied?: number };
  ok(openLeft.ok === true && openLeft.applied === 1, "a car with no open assignment inactivates without a close date");
  ok(psql("SELECT count(*) FROM public.assignment_history WHERE railcar_id = 3") === "0", "no assignment row was invented");
} catch (err) {
  failed += 1;
  console.error("FAIL", err instanceof Error ? err.message : err);
} finally {
  run(bin("pg_ctl"), ["-D", data, "stop"]);
  rmSync(root, { recursive: true, force: true });
}

console.log(`${passed} passed, ${failed} failed`);
if (failed) process.exit(1);
