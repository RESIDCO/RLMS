/**
 * Throwaway Postgres: remark undo still deletes car_number_history after the
 * tracker-sync migration replaces rlms_undo_change_group, and sync undo still
 * removes shops, shared column prefs, and an empty sync-created program.
 * Run: npx tsx shared/program-tracker-sync.pg.test.ts
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const PG_BIN = ["/usr/lib/postgresql/16/bin", "/usr/lib/postgresql/17/bin", "/usr/lib/postgresql/15/bin"].find((dir) =>
  existsSync(join(dir, "initdb")),
);

let passed = 0;
let failed = 0;
function ok(cond: boolean, label: string) {
  if (cond) passed += 1;
  else {
    failed += 1;
    console.error("FAIL", label);
  }
}

if (!PG_BIN) {
  console.error("FAIL postgres binaries not found");
  process.exit(1);
}

const root = mkdtempSync(join(tmpdir(), "tracker-sync-pg-"));
const data = join(root, "data");
const sock = root;
const port = "55433";
const migrations = join(import.meta.dirname, "../migrations");

function bin(name: string): string {
  return join(PG_BIN!, name);
}

function run(cmd: string, args: string[], input?: string): { status: number; stdout: string; stderr: string } {
  const res = spawnSync(cmd, args, { encoding: "utf8", input });
  return { status: res.status ?? 1, stdout: res.stdout ?? "", stderr: res.stderr ?? "" };
}

function psql(sql: string, database = "sync"): string {
  const res = run(bin("psql"), ["-h", sock, "-p", port, "-U", "postgres", "-d", database, "-v", "ON_ERROR_STOP=1", "-tA", "-c", sql]);
  if (res.status !== 0) throw new Error(res.stderr || res.stdout);
  return res.stdout.trim();
}

function psqlFile(file: string) {
  const res = run(bin("psql"), ["-h", sock, "-p", port, "-U", "postgres", "-d", "sync", "-v", "ON_ERROR_STOP=1", "-f", file]);
  if (res.status !== 0) throw new Error(`${file}\n${res.stderr || res.stdout}`);
}

const HELPERS = `
CREATE OR REPLACE FUNCTION public.rlms_jsonb_key_matches(cur jsonb, expected jsonb, k text)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE
    WHEN expected IS NULL OR NOT (expected ? k) THEN true
    WHEN expected -> k = 'null'::jsonb THEN
      cur -> k IS NULL OR cur -> k = 'null'::jsonb OR coalesce(cur ->> k, '') = ''
    WHEN jsonb_typeof(expected -> k) = 'boolean' THEN
      coalesce(cur ->> k, '') IN (
        CASE WHEN (expected ->> k)::boolean THEN 'true' ELSE 'false' END,
        CASE WHEN (expected ->> k)::boolean THEN 't' ELSE 'f' END
      )
    ELSE
      coalesce(left(cur ->> k, 10), '') IS NOT DISTINCT FROM coalesce(left(expected ->> k, 10), '')
      OR coalesce(cur ->> k, '') IS NOT DISTINCT FROM coalesce(expected ->> k, '')
  END;
$$;

CREATE OR REPLACE FUNCTION public.rlms_apply_jsonb_patch(p_table text, p_id bigint, p_patch jsonb)
RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE
  stmt text; col text; typ text; parts text[] := ARRAY[]::text[];
BEGIN
  IF p_patch IS NULL OR p_patch = '{}'::jsonb THEN RETURN; END IF;
  IF p_table <> 'railcars' THEN RAISE EXCEPTION 'undo: table % is not patchable', p_table; END IF;
  FOR col, typ IN
    SELECT a.attname, format_type(a.atttypid, a.atttypmod)
    FROM pg_attribute a
    JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relname = p_table AND a.attnum > 0 AND NOT a.attisdropped
  LOOP
    IF p_patch ? col THEN
      IF p_patch -> col = 'null'::jsonb THEN parts := array_append(parts, format('%I = NULL', col));
      ELSE parts := array_append(parts, format('%I = ($1->>%L)::%s', col, col, typ));
      END IF;
    END IF;
  END LOOP;
  IF coalesce(array_length(parts, 1), 0) = 0 THEN RETURN; END IF;
  stmt := format('UPDATE public.%I SET %s WHERE id = $2', p_table, array_to_string(parts, ', '));
  EXECUTE stmt USING p_patch, p_id;
END;
$fn$;
`;

try {
  const init = run(bin("initdb"), ["-D", data, "--username=postgres", "--auth=trust", "--no-sync"]);
  if (init.status !== 0) throw new Error(init.stderr || init.stdout);
  const start = run(bin("pg_ctl"), ["-D", data, "-o", `-p ${port} -k ${sock} -c listen_addresses=`, "-l", join(root, "log"), "start"]);
  if (start.status !== 0) throw new Error(start.stderr || start.stdout);
  psql("CREATE DATABASE sync", "postgres");
  psql(`
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE ROLE service_role;
    CREATE TABLE public.railcars (
      id bigint PRIMARY KEY,
      car_number text NOT NULL,
      reporting_marks text NOT NULL,
      car_initial text,
      old_car_initial text,
      old_car_number text,
      active boolean,
      status text,
      fleet_status text
    );
    CREATE TABLE public.car_number_history (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      railcar_id bigint NOT NULL REFERENCES public.railcars(id),
      old_car_initial text,
      old_car_number text NOT NULL,
      new_car_initial text,
      new_car_number text NOT NULL,
      changed_at timestamptz NOT NULL DEFAULT now(),
      changed_by text,
      reason text
    );
    CREATE TABLE public.activity_log (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      entity_type text NOT NULL,
      entity_id bigint NOT NULL,
      railcar_id bigint,
      rider_id bigint,
      action text NOT NULL,
      detail jsonb NOT NULL DEFAULT '{}'::jsonb,
      actor text,
      source text NOT NULL DEFAULT 'ui',
      occurred_at timestamptz NOT NULL DEFAULT now(),
      change_group uuid,
      table_name text,
      row_pk bigint,
      before jsonb,
      after jsonb,
      undoable boolean NOT NULL DEFAULT true,
      undo_of bigint,
      undone_at timestamptz,
      undone_by text
    );
    CREATE TABLE public.program_field_defs (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      category_id bigint NOT NULL,
      field_key text NOT NULL,
      label text NOT NULL,
      field_type text NOT NULL,
      section text,
      sort_order int
    );
    CREATE TABLE public.programs (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name text NOT NULL
    );
    CREATE TABLE public.program_cars (
      id bigint PRIMARY KEY,
      program_id bigint NOT NULL REFERENCES public.programs(id)
    );
    CREATE TABLE public.shops (
      id bigint PRIMARY KEY,
      name text NOT NULL
    );
    CREATE TABLE public.user_column_prefs (
      id bigint PRIMARY KEY,
      list_key text,
      view_name text,
      is_shared boolean,
      visible_cols jsonb
    );
    INSERT INTO public.railcars (id, car_number, reporting_marks, car_initial, active)
    VALUES (1, '310001', 'KCS', 'KCS', true);
  `);
  psql(HELPERS);
  const ordered = ["20261112_remark_in_place.sql", "20261113_program_global_optional_fields.sql"];
  ok(ordered.slice().sort().join(",") === ordered.join(","), "tracker sync migration sorts after remark in place");
  psqlFile(join(migrations, ordered[0]));

  const applied = JSON.parse(psql(`
    SELECT public.remark_railcars_in_place(
      jsonb_build_array(jsonb_build_object(
        'id', 1, 'old_reporting_marks', 'KCS', 'old_car_number', '310001',
        'reporting_marks', 'OFOX', 'car_number', '310001'
      )),
      'Remark in place test',
      'tester@residco.com',
      'actor-1'
    )::text
  `)) as { ok: boolean; change_group: string };
  ok(applied.ok === true, "remark in place commits before the sync migration");
  const group = applied.change_group;
  ok(psql(`SELECT count(*) FROM public.car_number_history WHERE reason LIKE '%change_group ${group}'`) === "1", "remark wrote a history row");

  psqlFile(join(migrations, ordered[1]));
  ok(psql("SELECT pg_get_functiondef('public.rlms_undo_change_group(uuid, text)'::regprocedure) LIKE '%hist_removed%'") === "t", "installed undo still names hist_removed");

  const undone = JSON.parse(psql(`SELECT public.rlms_undo_change_group('${group}'::uuid, 'actor-1')::text`)) as {
    ok: boolean;
    history_removed: number;
    restored: number;
  };
  ok(undone.ok === true && undone.restored === 1 && undone.history_removed === 1, "remark undo after the sync migration deletes the history row");
  ok(psql("SELECT reporting_marks || ' ' || car_number FROM public.railcars WHERE id = 1") === "KCS 310001", "remark undo restores the original mark");
  ok(psql("SELECT count(*) FROM public.car_number_history WHERE railcar_id = 1") === "0", "the remark history row is gone");

  const syncGroup = psql("SELECT gen_random_uuid()::text");
  psql(`
    INSERT INTO public.shops (id, name) VALUES (14, 'PFL-St Louis TRRA');
    INSERT INTO public.user_column_prefs (id, list_key, view_name, is_shared, visible_cols)
    VALUES (8, 'program_cars:1', 'Tracker order', true, '{"cols":["car"]}'::jsonb);
    INSERT INTO public.programs (id, name) VALUES (70, 'OL9999 - Created by sync');
    INSERT INTO public.activity_log (entity_type, entity_id, action, actor, detail, source, change_group, table_name, row_pk, before, after)
    VALUES
      ('program', 14, 'shop_created', 'actor-1', '{"op":"insert","source":"program_tracker_sync"}'::jsonb, 'program_tracker_sync', '${syncGroup}', 'shops', 14, '{}'::jsonb, '{"id":14,"name":"PFL-St Louis TRRA"}'::jsonb),
      ('program', 1, 'program_column_layout', 'actor-1', '{"op":"insert","source":"program_tracker_sync"}'::jsonb, 'program_tracker_sync', '${syncGroup}', 'user_column_prefs', 8, '{}'::jsonb, '{"id":8}'::jsonb),
      ('program', 70, 'program_created', 'actor-1', '{"op":"insert","source":"program_tracker_sync"}'::jsonb, 'program_tracker_sync', '${syncGroup}', 'programs', 70, '{}'::jsonb, '{"id":70,"name":"OL9999 - Created by sync"}'::jsonb);
  `);
  const syncUndo = JSON.parse(psql(`SELECT public.rlms_undo_change_group('${syncGroup}'::uuid, 'actor-1')::text`)) as { ok: boolean; restored: number };
  ok(syncUndo.ok === true && syncUndo.restored === 3, "sync undo restores the shop, layout, and empty program");
  ok(psql("SELECT count(*) FROM public.shops") === "0", "sync undo deletes the shop it created");
  ok(psql("SELECT count(*) FROM public.user_column_prefs") === "0", "sync undo deletes the shared column pref it created");
  ok(psql("SELECT count(*) FROM public.programs WHERE id = 70") === "0", "sync undo deletes a program that has no cars");

  const blocked = psql("SELECT gen_random_uuid()::text");
  psql(`
    INSERT INTO public.programs (id, name) VALUES (71, 'OL9998 - Has cars');
    INSERT INTO public.program_cars (id, program_id) VALUES (5, 71);
    INSERT INTO public.activity_log (entity_type, entity_id, action, actor, detail, source, change_group, table_name, row_pk, before, after)
    VALUES ('program', 71, 'program_created', 'actor-1', '{"op":"insert","source":"program_tracker_sync"}'::jsonb, 'program_tracker_sync', '${blocked}', 'programs', 71, '{}'::jsonb, '{"id":71}'::jsonb);
  `);
  psql(`
    DO $$
    BEGIN
      PERFORM public.rlms_undo_change_group('${blocked}'::uuid, 'actor-1');
      RAISE EXCEPTION 'undo should have refused';
    EXCEPTION WHEN OTHERS THEN
      IF SQLERRM NOT LIKE '%still has cars%' THEN
        RAISE;
      END IF;
    END $$;
  `);
  ok(psql("SELECT name FROM public.programs WHERE id = 71") === "OL9998 - Has cars", "sync undo leaves a program that still has cars");
  ok(psql("SELECT count(*) FROM public.program_cars WHERE program_id = 71") === "1", "the program's cars stay in place");

  psqlFile(join(migrations, "20261115_manage_columns.sql"));
  ok(psql("SELECT count(*) FROM public.program_field_defs WHERE field_key = 'trace_date_ran' AND program_id IS NULL") === "1", "trace date ran is a global optional column");
  const columnGroup = psql("SELECT gen_random_uuid()::text");
  psql(`
    INSERT INTO public.program_field_defs (id, category_id, program_id, field_key, label, field_type, section, sort_order, is_optional)
    VALUES (33, NULL, 71, 'local_note', 'Local note', 'text', 'Program', 2000, false);
    INSERT INTO public.activity_log (entity_type, entity_id, action, actor, detail, source, change_group, table_name, row_pk, before, after)
    VALUES ('program', 71, 'column_added', 'actor-1', '{"op":"insert"}'::jsonb, 'app', '${columnGroup}', 'program_field_defs', 33, '{}'::jsonb, '{"id":33,"label":"Local note"}'::jsonb);
  `);
  const columnUndo = JSON.parse(psql(`SELECT public.rlms_undo_change_group('${columnGroup}'::uuid, 'actor-1')::text`)) as { ok: boolean; restored: number };
  ok(columnUndo.ok === true && columnUndo.restored === 1, "undo of a new column retires it");
  ok(psql("SELECT count(*) FROM public.program_field_defs WHERE id = 33") === "1", "undo does not delete the column definition");
  ok(psql("SELECT retired_at IS NOT NULL FROM public.program_field_defs WHERE id = 33") === "t", "undo sets retired_at");
} catch (err) {
  failed += 1;
  console.error("FAIL", err instanceof Error ? err.message : err);
} finally {
  run(bin("pg_ctl"), ["-D", data, "stop"]);
  rmSync(root, { recursive: true, force: true });
}

console.log(`${passed} passed, ${failed} failed`);
if (failed) process.exit(1);
