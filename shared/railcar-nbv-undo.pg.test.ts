/**
 * Undo round-trip for a railcar edit that touches nbv numeric(12,2).
 * Run: npx tsx shared/railcar-nbv-undo.pg.test.ts
 *
 * Uses a throwaway cluster. Does not apply repo migrations to a shared database.
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { canonicalChangePair } from "./canonical-json";
import { currentMatchesAfter } from "./undo";

const PG_BIN = ["/usr/lib/postgresql/16/bin", "/usr/lib/postgresql/17/bin", "/usr/lib/postgresql/15/bin"].find((dir) =>
  existsSync(join(dir, "initdb")),
);

let passed = 0;
let failed = 0;
function ok(cond: boolean, label: string) {
  if (cond) passed += 1;
  else {
    failed += 1;
    console.error("FAIL", label);
  }
}

if (!PG_BIN) {
  console.error("FAIL postgres binaries not found");
  process.exit(1);
}

const root = mkdtempSync(join(tmpdir(), "nbv-undo-pg-"));
const data = join(root, "data");
const sock = root;
const port = "55442";

function bin(name: string): string {
  return join(PG_BIN!, name);
}

function run(cmd: string, args: string[], input?: string): { status: number; stdout: string; stderr: string } {
  const res = spawnSync(cmd, args, { encoding: "utf8", input });
  return { status: res.status ?? 1, stdout: res.stdout ?? "", stderr: res.stderr ?? "" };
}

function psql(sql: string, database = "nbvundo"): string {
  const res = run(bin("psql"), ["-h", sock, "-p", port, "-U", "postgres", "-d", database, "-v", "ON_ERROR_STOP=1", "-tA", "-c", sql]);
  if (res.status !== 0) throw new Error(res.stderr || res.stdout);
  return res.stdout.trim();
}

function psqlInput(sql: string): string {
  const res = run(bin("psql"), ["-h", sock, "-p", port, "-U", "postgres", "-d", "nbvundo", "-v", "ON_ERROR_STOP=1", "-tA"], sql);
  if (res.status !== 0) throw new Error(res.stderr || res.stdout);
  return res.stdout.trim();
}

function extractFunction(sql: string, name: string): string {
  const start = sql.indexOf(`CREATE OR REPLACE FUNCTION public.${name}`);
  if (start < 0) throw new Error(`missing ${name}`);
  const end = sql.indexOf("$function$;", start);
  if (end < 0) throw new Error(`missing end of ${name}`);
  return sql.slice(start, end + "$function$;".length);
}

try {
  const init = run(bin("initdb"), ["-D", data, "--username=postgres", "--auth=trust", "--no-sync"]);
  if (init.status !== 0) throw new Error(init.stderr || init.stdout);
  const start = run(bin("pg_ctl"), ["-D", data, "-o", `-p ${port} -k ${sock} -c listen_addresses=`, "-l", join(root, "log"), "start"]);
  if (start.status !== 0) throw new Error(start.stderr || start.stdout);
  psql("CREATE DATABASE nbvundo", "postgres");
  psqlInput(`
    CREATE EXTENSION IF NOT EXISTS pgcrypto;
    CREATE ROLE service_role;
    CREATE TABLE public.railcars (
      id bigint PRIMARY KEY,
      car_number text NOT NULL,
      reporting_marks text NOT NULL,
      status text NOT NULL DEFAULT 'Active/In-Service',
      active boolean NOT NULL DEFAULT true,
      entity text,
      managed_category text,
      nbv numeric(12,2)
    );
    CREATE OR REPLACE FUNCTION public.railcars_derive_managed_category() RETURNS trigger AS $$
    BEGIN
      IF NEW.entity IS NULL THEN
        NEW.managed_category := COALESCE(NEW.managed_category, NULL);
      ELSIF NEW.entity = 'Main' THEN
        NEW.managed_category := 'RESIDCO Owned';
      ELSE
        NEW.managed_category := COALESCE(NEW.managed_category, NEW.entity);
      END IF;
      RETURN NEW;
    END;
    $$ LANGUAGE plpgsql;
    CREATE TRIGGER railcars_derive_managed_category_trg
      BEFORE INSERT OR UPDATE OF entity ON public.railcars
      FOR EACH ROW EXECUTE FUNCTION public.railcars_derive_managed_category();
    CREATE TABLE public.activity_log (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      entity_type text,
      entity_id bigint,
      action text,
      actor text,
      railcar_id bigint,
      rider_id bigint,
      detail jsonb,
      source text,
      occurred_at timestamptz NOT NULL DEFAULT now(),
      change_group uuid,
      table_name text,
      row_pk bigint,
      before jsonb,
      after jsonb,
      undoable boolean,
      undo_of bigint,
      undone_at timestamptz,
      undone_by text
    );
    CREATE TABLE public.car_number_history (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      railcar_id bigint,
      reason text
    );
    CREATE TABLE public.car_status_history (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      car_id bigint,
      event_type text,
      reason text,
      created_by text,
      from_status text,
      to_status text
    );
    CREATE TABLE public.program_field_defs (id bigint PRIMARY KEY, retired_at timestamptz);
    CREATE TABLE public.programs (id bigint PRIMARY KEY);
    CREATE TABLE public.program_cars (id bigint PRIMARY KEY, program_id bigint, exited_date date);
    CREATE TABLE public.car_commitments (id bigint PRIMARY KEY, cleared_at timestamptz);
    INSERT INTO public.railcars (id, car_number, reporting_marks, entity, managed_category, nbv)
    VALUES (1, '349699', 'OFCX', 'Trinity', 'Keep me', 100.00);
    REVOKE ALL ON FUNCTION public.railcars_derive_managed_category() FROM PUBLIC;
    GRANT EXECUTE ON FUNCTION public.railcars_derive_managed_category() TO service_role;
  `);

  const matchSql = `
    CREATE OR REPLACE FUNCTION public.rlms_jsonb_key_matches(cur jsonb, expected jsonb, k text)
    RETURNS boolean
    LANGUAGE sql
    IMMUTABLE
    AS $$
      SELECT CASE
        WHEN expected IS NULL OR NOT (expected ? k) THEN true
        WHEN expected -> k = 'null'::jsonb THEN
          cur -> k IS NULL OR cur -> k = 'null'::jsonb OR coalesce(cur ->> k, '') = ''
        WHEN jsonb_typeof(expected -> k) = 'boolean' THEN
          coalesce(cur ->> k, '') IN (
            CASE WHEN (expected ->> k)::boolean THEN 'true' ELSE 'false' END,
            CASE WHEN (expected ->> k)::boolean THEN 't' ELSE 'f' END
          )
        ELSE
          coalesce(left(cur ->> k, 10), '') IS NOT DISTINCT FROM coalesce(left(expected ->> k, 10), '')
          OR coalesce(cur ->> k, '') IS NOT DISTINCT FROM coalesce(expected ->> k, '')
      END;
    $$;
    REVOKE ALL ON FUNCTION public.rlms_jsonb_key_matches(jsonb, jsonb, text) FROM PUBLIC;
    GRANT EXECUTE ON FUNCTION public.rlms_jsonb_key_matches(jsonb, jsonb, text) TO service_role;
  `;
  psqlInput(matchSql);

  const latest = readFileSync(join(import.meta.dirname, "../migrations/20261118_crm_bid_p1.sql"), "utf8");
  psqlInput(extractFunction(latest, "rlms_apply_jsonb_patch"));
  psqlInput(extractFunction(latest, "rlms_undo_change_group"));
  psqlInput(`
    REVOKE ALL ON FUNCTION public.rlms_apply_jsonb_patch(text, bigint, jsonb) FROM PUBLIC;
    REVOKE ALL ON FUNCTION public.rlms_undo_change_group(uuid, text) FROM PUBLIC;
    GRANT EXECUTE ON FUNCTION public.rlms_apply_jsonb_patch(text, bigint, jsonb) TO service_role;
    GRANT EXECUTE ON FUNCTION public.rlms_undo_change_group(uuid, text) TO service_role;
  `);

  const beforeText = psql("SELECT to_jsonb(r)::text FROM public.railcars r WHERE id = 1");
  psql("UPDATE public.railcars SET nbv = 0 WHERE id = 1");
  const afterText = psql("SELECT to_jsonb(r)::text FROM public.railcars r WHERE id = 1");
  ok(psql("SELECT managed_category FROM public.railcars WHERE id = 1") === "Keep me", "writing nbv does not re-force managed_category");
  const pair = canonicalChangePair(beforeText, afterText, ["nbv"]);
  ok(pair != null && pair.keys.length === 1 && pair.afterJson.includes("0.00"), "RETURNING text logs a single scaled nbv");

  const collapsed = psql(`SELECT '{"nbv":0}'::jsonb ->> 'nbv'`);
  ok(collapsed === "0", "jsonb number 0 is the text 0");
  ok(!currentMatchesAfter({ nbv: "0.00" }, { nbv: "0" }), "preview refuses the collapsed nbv");
  ok(currentMatchesAfter({ nbv: "0.00" }, { nbv: "0.00" }), "preview accepts canonical 0.00");

  const badGroup = "11111111-1111-4111-8111-111111111111";
  psqlInput(`
    INSERT INTO public.activity_log (entity_type, entity_id, action, actor, railcar_id, detail, source, change_group, table_name, row_pk, before, after, undoable)
    VALUES ('railcar', 1, 'railcar_patch', 'editor', 1, '{"op":"update"}'::jsonb, 'ui', '${badGroup}', 'railcars', 1, '${pair!.beforeJson}'::jsonb, '{"nbv":0}'::jsonb, true);
  `);
  const bad = psql(`SELECT public.rlms_undo_change_group('${badGroup}'::uuid, 'editor')::text`);
  ok(bad.includes('"ok": false') && bad.includes("changed since (nbv)"), "collapsed 0 conflicts with stored 0.00");
  ok(psql("SELECT nbv::text FROM public.railcars WHERE id = 1") === "0.00", "conflict leaves the car at 0.00");

  const goodGroup = "22222222-2222-4222-8222-222222222222";
  psqlInput(`
    INSERT INTO public.activity_log (entity_type, entity_id, action, actor, railcar_id, detail, source, change_group, table_name, row_pk, before, after, undoable)
    VALUES ('railcar', 1, 'railcar_patch', 'editor', 1, '{"op":"update"}'::jsonb, 'ui', '${goodGroup}', 'railcars', 1, '${pair!.beforeJson}'::jsonb, '${pair!.afterJson}'::jsonb, true);
  `);
  ok(psql(`SELECT count(*) FROM jsonb_object_keys((SELECT after FROM public.activity_log WHERE change_group = '${goodGroup}'));`) === "1", "the logged after object has one key");
  ok(psql(`SELECT after->>'nbv' FROM public.activity_log WHERE change_group = '${goodGroup}'`) === "0.00", "logged after.nbv is 0.00");
  const undone = psql(`SELECT public.rlms_undo_change_group('${goodGroup}'::uuid, 'editor')::text`);
  ok(undone.includes('"ok": true'), "canonical nbv undo succeeds");
  ok(psql("SELECT nbv::text FROM public.railcars WHERE id = 1") === "100.00", "undo restores nbv 100.00");
  ok(psql("SELECT managed_category FROM public.railcars WHERE id = 1") === "Keep me", "undo leaves managed_category alone");
} catch (err) {
  failed += 1;
  console.error("FAIL", err instanceof Error ? err.message : err);
} finally {
  run(bin("pg_ctl"), ["-D", data, "stop", "-m", "immediate"]);
  rmSync(root, { recursive: true, force: true });
}

console.log(`${passed} passed, ${failed} failed`);
if (failed) process.exit(1);
