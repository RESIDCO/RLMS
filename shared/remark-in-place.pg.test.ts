/* eslint-disable no-console */
/**
 * Executes remark_railcars_in_place on a throwaway Postgres cluster.
 * Run: npx tsx shared/remark-in-place.pg.test.ts
 *
 * The postcheck used to join jsonb_array_elements(...) item while `item` was
 * already a PL/pgSQL variable, so every apply raised
 * "column reference item is ambiguous" and rolled back.
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const PG_BIN = ["/usr/lib/postgresql/16/bin", "/usr/lib/postgresql/17/bin", "/usr/lib/postgresql/15/bin"].find((dir) =>
  existsSync(join(dir, "initdb")),
);

let passed = 0;
let failed = 0;
function ok(cond: boolean, label: string) {
  if (cond) passed += 1;
  else {
    failed += 1;
    console.error("FAIL", label);
  }
}

if (!PG_BIN) {
  console.error("FAIL postgres binaries not found");
  process.exit(1);
}

const root = mkdtempSync(join(tmpdir(), "remark-pg-"));
const data = join(root, "data");
const sock = root;
const port = "55432";
const migration = join(import.meta.dirname, "../migrations/20261112_remark_in_place.sql");

function bin(name: string): string {
  return join(PG_BIN!, name);
}

function run(cmd: string, args: string[], input?: string): { status: number; stdout: string; stderr: string } {
  const res = spawnSync(cmd, args, { encoding: "utf8", input });
  return { status: res.status ?? 1, stdout: res.stdout ?? "", stderr: res.stderr ?? "" };
}

function psql(sql: string, database = "remark"): string {
  const res = run(bin("psql"), ["-h", sock, "-p", port, "-U", "postgres", "-d", database, "-v", "ON_ERROR_STOP=1", "-tA", "-c", sql]);
  if (res.status !== 0) throw new Error(res.stderr || res.stdout);
  return res.stdout.trim();
}

function psqlFile(file: string) {
  const res = run(bin("psql"), ["-h", sock, "-p", port, "-U", "postgres", "-d", "remark", "-v", "ON_ERROR_STOP=1", "-f", file]);
  if (res.status !== 0) throw new Error(res.stderr || res.stdout);
}

const HELPERS = `
CREATE OR REPLACE FUNCTION public.rlms_jsonb_key_matches(cur jsonb, expected jsonb, k text)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE
    WHEN expected IS NULL OR NOT (expected ? k) THEN true
    WHEN expected -> k = 'null'::jsonb THEN
      cur -> k IS NULL OR cur -> k = 'null'::jsonb OR coalesce(cur ->> k, '') = ''
    WHEN jsonb_typeof(expected -> k) = 'boolean' THEN
      coalesce(cur ->> k, '') IN (
        CASE WHEN (expected ->> k)::boolean THEN 'true' ELSE 'false' END,
        CASE WHEN (expected ->> k)::boolean THEN 't' ELSE 'f' END
      )
    ELSE
      coalesce(left(cur ->> k, 10), '') IS NOT DISTINCT FROM coalesce(left(expected ->> k, 10), '')
      OR coalesce(cur ->> k, '') IS NOT DISTINCT FROM coalesce(expected ->> k, '')
  END;
$$;

CREATE OR REPLACE FUNCTION public.rlms_apply_jsonb_patch(p_table text, p_id bigint, p_patch jsonb)
RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE
  stmt text; col text; typ text; parts text[] := ARRAY[]::text[];
BEGIN
  IF p_patch IS NULL OR p_patch = '{}'::jsonb THEN RETURN; END IF;
  IF p_table <> 'railcars' THEN RAISE EXCEPTION 'undo: table % is not patchable', p_table; END IF;
  FOR col, typ IN
    SELECT a.attname, format_type(a.atttypid, a.atttypmod)
    FROM pg_attribute a
    JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relname = p_table AND a.attnum > 0 AND NOT a.attisdropped
  LOOP
    IF p_patch ? col THEN
      IF p_patch -> col = 'null'::jsonb THEN parts := array_append(parts, format('%I = NULL', col));
      ELSE parts := array_append(parts, format('%I = ($1->>%L)::%s', col, col, typ));
      END IF;
    END IF;
  END LOOP;
  IF coalesce(array_length(parts, 1), 0) = 0 THEN RETURN; END IF;
  stmt := format('UPDATE public.%I SET %s WHERE id = $2', p_table, array_to_string(parts, ', '));
  EXECUTE stmt USING p_patch, p_id;
END;
$fn$;
`;

try {
  const init = run(bin("initdb"), ["-D", data, "--username=postgres", "--auth=trust", "--no-sync"]);
  if (init.status !== 0) throw new Error(init.stderr || init.stdout);
  const start = run(bin("pg_ctl"), ["-D", data, "-o", `-p ${port} -k ${sock} -c listen_addresses=`, "-l", join(root, "log"), "start"]);
  if (start.status !== 0) throw new Error(start.stderr || start.stdout);
  psql("CREATE DATABASE remark", "postgres");
  psql(`
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE ROLE service_role;
    CREATE TABLE public.railcars (
      id bigint PRIMARY KEY,
      car_number text NOT NULL,
      reporting_marks text NOT NULL,
      car_initial text,
      old_car_initial text,
      old_car_number text,
      active boolean,
      status text,
      fleet_status text
    );
    CREATE TABLE public.car_number_history (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      railcar_id bigint NOT NULL REFERENCES public.railcars(id),
      old_car_initial text,
      old_car_number text NOT NULL,
      new_car_initial text,
      new_car_number text NOT NULL,
      changed_at timestamptz NOT NULL DEFAULT now(),
      changed_by text,
      reason text
    );
    CREATE TABLE public.activity_log (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      entity_type text NOT NULL,
      entity_id bigint NOT NULL,
      railcar_id bigint,
      rider_id bigint,
      action text NOT NULL,
      detail jsonb NOT NULL DEFAULT '{}'::jsonb,
      actor text,
      source text NOT NULL DEFAULT 'ui',
      occurred_at timestamptz NOT NULL DEFAULT now(),
      change_group uuid,
      table_name text,
      row_pk bigint,
      before jsonb,
      after jsonb,
      undoable boolean NOT NULL DEFAULT true,
      undo_of bigint,
      undone_at timestamptz,
      undone_by text
    );
    INSERT INTO public.railcars (id, car_number, reporting_marks, car_initial, active)
    VALUES
      (1, '310001', 'KCS', 'KCS', true),
      (2, '310002', 'KCS', 'KCS', true),
      (3, '310003', 'KCS', 'KCS', true);
  `);
  psql(HELPERS);
  psqlFile(migration);

  ok(psql("SELECT 1 FROM pg_indexes WHERE indexname = 'idx_car_number_history_old_mark_number'") === "1", "old-mark index exists");

  const appliedRaw = psql(`
    SELECT public.remark_railcars_in_place(
      jsonb_build_array(
        jsonb_build_object('id', 1, 'old_reporting_marks', 'KCS', 'old_car_number', '310001', 'reporting_marks', 'OFOX', 'car_number', '310001'),
        jsonb_build_object('id', 2, 'old_reporting_marks', 'KCS', 'old_car_number', '310002', 'reporting_marks', 'OFOX', 'car_number', '310002')
      ),
      'Remark in place test',
      'tester@residco.com',
      'actor-1'
    )::text
  `);
  const applied = JSON.parse(appliedRaw) as { ok: boolean; change_group: string; results: Array<{ id: number }> };
  ok(applied.ok === true, "apply commits instead of rolling back on the postcheck");
  ok(applied.results.length === 2 && applied.results.every((row) => row.id === 1 || row.id === 2), "apply keeps the railcar ids");

  const marks = psql("SELECT id::text || ':' || reporting_marks || ':' || car_number || ':' || coalesce(old_car_initial, '') FROM public.railcars WHERE id IN (1, 2) ORDER BY id");
  ok(marks === "1:OFOX:310001:KCS\n2:OFOX:310002:KCS", "both cars renamed in place");
  ok(psql("SELECT reporting_marks FROM public.railcars WHERE id = 3") === "KCS", "a car outside the batch is unchanged");

  const group = applied.change_group;
  ok(psql(`SELECT count(*) FROM public.car_number_history WHERE reason LIKE '%change_group ${group}'`) === "2", "one history row per remarked car");
  ok(
    psql(`SELECT count(*) FROM public.activity_log WHERE change_group = '${group}' AND action = 'mark_change' AND undoable IS TRUE AND detail->>'op' = 'update' AND railcar_id IN (1, 2)`) === "2",
    "undoable mark_change rows share one change group",
  );

  psql(`
    INSERT INTO public.car_number_history (railcar_id, old_car_initial, old_car_number, new_car_initial, new_car_number, reason)
    VALUES
      (1, 'OLD1', '310001', 'KCS', '310001', 'older remark, not this batch'),
      (3, 'KCS', '310003', 'KEEP', '310003', 'decoy; change_group ${group}');
  `);

  const undone = JSON.parse(psql(`SELECT public.rlms_undo_change_group('${group}'::uuid, 'actor-1')::text`)) as {
    ok: boolean;
    history_removed: number;
    restored: number;
  };
  ok(undone.ok === true && undone.restored === 2 && undone.history_removed === 2, "undo restores both cars and deletes only their history rows");
  ok(psql("SELECT reporting_marks || ' ' || car_number FROM public.railcars WHERE id = 1") === "KCS 310001", "undo puts the original mark back");
  ok(psql("SELECT coalesce(old_car_initial, '') FROM public.railcars WHERE id = 1") === "", "undo restores the previous old mark");
  ok(psql("SELECT count(*) FROM public.car_number_history WHERE railcar_id IN (1, 2) AND reason LIKE '%change_group %'") === "0", "remark history rows are gone");
  ok(psql("SELECT reason FROM public.car_number_history WHERE railcar_id = 1") === "older remark, not this batch", "unrelated history on a remarked car stays");
  ok(psql(`SELECT count(*) FROM public.car_number_history WHERE railcar_id = 3 AND reason LIKE '%change_group ${group}'`) === "1", "the same change_group text on another car is not deleted");
} catch (err) {
  failed += 1;
  console.error("FAIL", err instanceof Error ? err.message : err);
} finally {
  run(bin("pg_ctl"), ["-D", data, "stop"]);
  rmSync(root, { recursive: true, force: true });
}

console.log(`${passed} passed, ${failed} failed`);
if (failed) process.exit(1);
